CREATE TABLE IF NOT EXISTS users (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, email VARCHAR(255) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(25) NOT NULL,
 console_access VARCHAR(25), department VARCHAR(100) NOT NULL DEFAULT '',
 status VARCHAR(15) NOT NULL DEFAULT 'Active', failed_attempts INT NOT NULL DEFAULT 0,
 locked_until TIMESTAMP NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_login TIMESTAMP NULL
);
CREATE TABLE IF NOT EXISTS audit_entries (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, actor VARCHAR(255) NOT NULL,
 action VARCHAR(100) NOT NULL, target VARCHAR(255) NOT NULL,
 success BOOLEAN NOT NULL, timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
